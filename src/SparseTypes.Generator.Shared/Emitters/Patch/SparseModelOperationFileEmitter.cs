using System.Collections.Immutable;
using System.Linq;
using System.Threading;

namespace SparseTypes.Generator.Shared;

/// <summary>Per-model Builder/Paths implementation file shell.</summary>
/// <remarks>Moves model operations into an external container.</remarks>
internal static class SparseModelOperationFileEmitter
{
    /// <summary>Opens the implementation file and the patch operation container.</summary>
    /// <param name="code">Implementation file builder (offset for container depth).</param>
    /// <param name="model">Model identity.</param>
    /// <param name="modelType">Qualified model type name.</param>
    /// <param name="members">Analyzed members.</param>
    /// <param name="dialect">Product patch dialect.</param>
    /// <param name="plan">Effective emission features.</param>
    /// <param name="implementationNamespace">Explicit implementation namespace.</param>
    /// <param name="container">Per-model implementation container name.</param>
    /// <param name="canApplyPatchInPlace">Whether the patch in-place result exists.</param>
    /// <param name="cancellationToken">Cooperative cancellation.</param>
    public static void OpenImplementation(
        SharedIndentedBuilder code,
        SparseModelInfo model,
        string modelType,
        ImmutableArray<SparseMemberModel> members,
        SparseFragmentPatchEmitter.SparsePatchDialect dialect,
        SparseEmissionFeatures plan,
        string implementationNamespace,
        string container,
        bool canApplyPatchInPlace,
        CancellationToken cancellationToken
    )
    {
        _ = cancellationToken;
        code.AppendLine("// <auto-generated />");
        code.AppendLine("#nullable enable");
        if (HasNullableKeyedMember(members))
        {
            code.AppendLine(
                "#pragma warning disable CS8714 // Present nullable values are valid dictionary keys."
            );
        }
        SparseModelOperationAliases.Append(
            code,
            SparseModelOperationAliases.Collect(
                modelType,
                members,
                dialect,
                plan,
                canApplyPatchInPlace
            )
        );
        code.AppendLine();
        code.Append("namespace ").Append(implementationNamespace).AppendLine();
        code.OpenBlock();
        var accessibility = model.IsPublic ? "public" : "internal";
        code.AppendLine(
            "/// <summary>Per-model generated operations for '"
                + modelType
                + "'. Backs the model-facing Patch and ChangeSet facades.</summary>"
        );
        code.AppendLine(
            "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]"
        );
        code.AppendLine(accessibility + " static partial class " + container);
        code.OpenBlock();
    }

    /// <summary>Opens one operation container class.</summary>
    /// <param name="code">Implementation file builder.</param>
    /// <param name="simpleName">Operation class simple name.</param>
    /// <param name="backedFacade">Backed facade description for docs.</param>
    public static void OpenOperations(
        SharedIndentedBuilder code,
        string simpleName,
        string backedFacade
    )
    {
        code.AppendLine(
            "/// <summary>Model-specific "
                + backedFacade
                + " algorithms backing the thin model facade.</summary>"
        );
        code.AppendLine("internal static class " + simpleName);
        code.OpenBlock();
    }

    /// <summary>Closes one operation container class.</summary>
    /// <param name="code">Implementation file builder.</param>
    public static void CloseOperations(SharedIndentedBuilder code) => code.CloseBlock();

    /// <summary>Closes the per-model container and its namespace.</summary>
    /// <param name="code">Implementation file builder.</param>
    public static void CloseImplementation(SharedIndentedBuilder code)
    {
        code.CloseBlock();
        code.CloseBlock();
    }

    private static bool HasNullableKeyedMember(ImmutableArray<SparseMemberModel> members) =>
        members.Any(static member =>
            SparseKeyedCollectionEmitter.IsKeyedSequence(member)
            && member.Collection.KeyTypeName?.EndsWith("?", System.StringComparison.Ordinal) == true
        );
}

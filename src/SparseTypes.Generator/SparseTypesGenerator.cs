    private static SparseGenerationResult RenderSinglePromoted(
        SparsePromotedModel promoted,
        bool bclHashSetImplementsReadOnlySet,
        bool bclHashSetSupportsCapacity,
        bool allowFileScopedTypes,
        SparseStjCapabilities stjCapabilities,
        CancellationToken cancellationToken
    )
    {
        cancellationToken.ThrowIfCancellationRequested();
        // Promoted collisions stay render-time (the promoted path carries no
        // analysis diagnostics) but run on the shared collision primitive.
        var promotedCollision = SparseShapeValidation.FindFirstReservedNameCollision(promoted.Members, Configuration.EffectiveReservedGeneratedNames);
        if (promotedCollision is not null)
        {
            return new SparseGenerationResult(
                null,
                null,
                ImmutableArray.Create(
                    new SparseGeneratorDiagnostic(Configuration.EffectiveDiagnosticIds.GeneratedNameCollision, null, promotedCollision)
                )
            );
        }

        var hint = SparseFragmentEmitter.GetPromotedHintName(promoted.Model, Configuration.PromotedHintNameSuffix, cancellationToken);
        var configuration = WithCapabilities(Configuration, allowFileScopedTypes, stjCapabilities);
        var implementationNamespace = SparseGeneratedPlacement.TryGetImplementationNamespace(configuration);
        Action<SharedIndentedBuilder>? appendModelMembers = null;
        if (implementationNamespace is not null)
        {
            var runtime = configuration.RuntimeDialect ?? throw new InvalidOperationException("A runtime dialect is required for source emission.");
            appendModelMembers = code =>
                SparseModelImplementationEmitter.AppendModelMembers(
                    code,
                    promoted.Model,
                    promoted.Members,
                    promoted.ReadOnlyViewModels,
                    configuration,
                    runtime.Namespace,
                    implementationNamespace
                );
        }

        var (surface, implementation) = SparsePerModelEmitter.BuildPromotedSplitSurface(
            promoted,
            bclHashSetImplementsReadOnlySet,
            bclHashSetSupportsCapacity,
            cancellationToken,
            configuration,
            appendModelMembers
        );
        var additional = ImmutableArray<SparseGeneratedSource>.Empty;
        if (implementation.HasValue)
        {
            additional = additional.Add(implementation.Value);
        }

        var merged = MergePerModelSources(surface, additional);
        return new SparseGenerationResult(hint, merged, ImmutableArray<SparseGeneratorDiagnostic>.Empty, ImmutableArray<SparseGeneratedSource>.Empty);
    }

    private static string MergePerModelSources(string surface, ImmutableArray<SparseGeneratedSource> additional) =>
        SparseTypesSingleFileMerger.Merge(surface, additional);

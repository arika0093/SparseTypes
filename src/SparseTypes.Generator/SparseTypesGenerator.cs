    /// <summary>Whether the product feature selection can emit any JSON converter family.</summary>
    /// <remarks>Shared JSON codec content follows this flag so compilations without JSON families keep empty shells.</remarks>
    private static bool EmitsJsonFamily() =>
        Configuration.EffectiveEmissionFeatures.EmitJsonConverters || Configuration.EffectiveEmissionFeatures.EmitChangePayload;

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var analyzed = context
            .SyntaxProvider.ForAttributeWithMetadataName(
                ModelAttributeName,
                static (node, _) => node is TypeDeclarationSyntax,
                static (attributeContext, cancellationToken) =>
                    SparseModelAnalyzer.Analyze((INamedTypeSymbol)attributeContext.TargetSymbol, Configuration, cancellationToken)
            )
            .WithTrackingName("SparseTypesGenerator.Analysis");
        var bclSetSupport = context
            .CompilationProvider.Select(
                static (compilation, _) =>
                    (
                        ReadOnlySet: SparseCollectionAnalyzer.HashSetImplementsReadOnlySet(compilation),
                        Capacity: SparseCollectionAnalyzer.HashSetSupportsCapacity(compilation)
                    )
            )
            .WithComparer(EqualityComparer<(bool ReadOnlySet, bool Capacity)>.Default)
            .WithTrackingName("SparseTypesGenerator.BclSetSupport");
        // Consumer language version drives file-scoped narrowing: file-local
        // helpers require C# 11+, older consumers keep internal helpers.
        var allowFileScopedTypes = context
            .CompilationProvider.Select(
                static (compilation, cancellationToken) =>
                {
                    cancellationToken.ThrowIfCancellationRequested();
                    if (compilation is Microsoft.CodeAnalysis.CSharp.CSharpCompilation csharp)
                    {
                        return (int)csharp.LanguageVersion >= 1100;
                    }

                    return false;
                }
            )
            .WithComparer(EqualityComparer<bool>.Default)
            .WithTrackingName("SparseTypesGenerator.FileScopedTypes");
        // Consumer System.Text.Json API surface: probed from referenced
        // symbols, never from the TFM or host dependencies.
        var stjCapabilities = CreateStjCapabilitiesProvider(context);
        var generated = analyzed
            .Combine(bclSetSupport)
            .Combine(allowFileScopedTypes)
            .Combine(stjCapabilities)
            .Select(
                static (input, cancellationToken) =>
                    Render(
                        input.Left.Left.Left,
                        input.Left.Left.Right.ReadOnlySet,
                        input.Left.Left.Right.Capacity,
                        input.Left.Right,
                        input.Right,
                        cancellationToken
                    )
            )
            .WithTrackingName("SparseTypesGenerator.Output");

        context.RegisterSourceOutput(generated, static (productionContext, result) => Emit(productionContext, result));

        var promotedPerRoot = analyzed
            .Select(static (analysis, _) => analysis.PromotedModels)
            .WithTrackingName("SparseTypesGenerator.PromotedPerRoot");
        var promotedContributions = promotedPerRoot
            .SelectMany(static (models, _) => models.IsDefault ? ImmutableArray<SparsePromotedModel>.Empty : models)
            .WithTrackingName("SparseTypesGenerator.PromotedContributions");
        var explicitRootNames = analyzed
            .Select(static (analysis, _) => analysis.Model?.ModelTypeName)
            .Where(static name => name is not null)
            .Select(static (name, _) => name!)
            .WithTrackingName("SparseTypesGenerator.ExplicitRoots")
            .Collect();
        var promotedDedup = promotedContributions
            .Collect()
            .Combine(explicitRootNames)
            .Select(static (input, cancellationToken) => SparsePromotedAggregation.Deduplicate(input.Left, input.Right, cancellationToken))
            .WithTrackingName("SparseTypesGenerator.PromotedDedup");
        var distinctPromoted = promotedDedup
            .SelectMany(static (result, _) => result.Distinct)
            .WithTrackingName("SparseTypesGenerator.PromotedDistinct");
        var promotedSources = distinctPromoted
            .Combine(bclSetSupport)
            .Combine(allowFileScopedTypes)
            .Combine(stjCapabilities)
            .Select(
                static (input, cancellationToken) =>
                    RenderSinglePromoted(
                        input.Left.Left.Left,
                        input.Left.Left.Right.ReadOnlySet,
                        input.Left.Left.Right.Capacity,
                        input.Left.Right,
                        input.Right,
                        cancellationToken
                    )
            )
            .WithTrackingName("SparseTypesGenerator.Promoted");
        context.RegisterSourceOutput(promotedSources, static (productionContext, result) => Emit(productionContext, result));
        var promotedConflicts = promotedDedup
            .SelectMany(static (result, _) => result.Incompatible)
            .Select(
                static (entry, _) =>
                    new SparseGenerationResult(
                        null,
                        null,
                        ImmutableArray.Create(
                            new SparseGeneratorDiagnostic(SparseTypesDiagnosticIds.IncompatiblePromotedModel, null, entry.DisplayName)
                        )
                    )
            )
            .WithTrackingName("SparseTypesGenerator.PromotedConflicts");
        context.RegisterSourceOutput(promotedConflicts, static (productionContext, result) => Emit(productionContext, result));

        var hasModels = analyzed
            .Select(static (analysis, _) => analysis.Model.HasValue)
            .Collect()
            .Select(static (presence, _) => presence.Any(static value => value))
            .WithComparer(EqualityComparer<bool>.Default);
        var generatedOncePlan = analyzed
            .Collect()
            .Combine(promotedDedup)
            .Combine(bclSetSupport)
            .Select(
                static (input, cancellationToken) =>
                    SparseGeneratedCapabilityPlanner.Aggregate(
                        input.Left.Left,
                        input.Left.Right.Distinct,
                        Configuration.EffectiveEmissionFeatures,
                        input.Right.ReadOnlySet,
                        input.Right.Capacity,
                        cancellationToken
                    )
            )
            .WithComparer(EqualityComparer<SparseGeneratedOncePlan>.Default)
            .WithTrackingName("SparseTypesGenerator.GeneratedOncePlan");
        var generatedOnceErrors = generatedOncePlan
            .Select(static (plan, _) => SparseGeneratedCapabilityPlanner.Validate(plan, Configuration.EffectiveEmissionFeatures))
            .WithComparer(EqualityComparer<ImmutableArray<string>>.Default)
            .WithTrackingName("SparseTypesGenerator.GeneratedOnceValidation");
        context.RegisterSourceOutput(
            generatedOnceErrors,
            static (productionContext, errors) =>
            {
                foreach (var message in errors)
                {
                    productionContext.ReportDiagnostic(Diagnostic.Create(InvalidEmissionPlan, Location.None, message));
                }
            }
        );
        // Partial System.Text.Json surface with JSON families requested: see
        // RegisterStjSurfaceValidation for the omission-plus-diagnostic policy.
        RegisterStjSurfaceValidation(context, stjCapabilities, hasModels);
        // Session cores live in the SparseTypes runtime (SparseTypes.Generated);
        // the generator only emits the per-model adapters that bind to them.
        // Emit shared helpers from the capability plan.
        var clonePlan = generatedOncePlan
            .Select(
                static (plan, _) =>
                    (
                        Needed: plan.Has(SparseGeneratedCapability.CloneKernels),
                        Portable: plan.NeedsPortableSetView,
                        Capacity: plan.HashSetSupportsCapacity
                    )
            )
            .WithComparer(EqualityComparer<(bool Needed, bool Portable, bool Capacity)>.Default)
            .WithTrackingName("SparseTypesGenerator.GeneratedOnceCloneKernels");
        context.RegisterSourceOutput(
            clonePlan,
            static (productionContext, plan) =>
            {
                var implementationNamespace = SparseGeneratedOnceEmitter.TryGetNamespace(Configuration);
                if (plan.Needed && implementationNamespace is not null)
                {
                    productionContext.AddSource(
                        SparseGeneratedOnceEmitter.CloneKernelsHintName(implementationNamespace),
                        SourceText.From(
                            SparseGeneratedOnceEmitter.RenderCloneKernels(
                                implementationNamespace,
                                plan.Portable,
                                plan.Capacity,
                                productionContext.CancellationToken
                            ),
                            Encoding.UTF8
                        )
                    );
                }
            }
        );
        var needsReadOnlyAdapters = generatedOncePlan
            .Select(static (plan, _) => plan.Has(SparseGeneratedCapability.ReadOnlyAdapters))
            .WithComparer(EqualityComparer<bool>.Default)
            .WithTrackingName("SparseTypesGenerator.GeneratedOnceReadOnlyAdapters");
        context.RegisterSourceOutput(
            needsReadOnlyAdapters,
            static (productionContext, emit) =>
            {
                var implementationNamespace = SparseGeneratedOnceEmitter.TryGetNamespace(Configuration);
                if (emit && implementationNamespace is not null)
                {
                    productionContext.AddSource(
                        SparseGeneratedOnceEmitter.ReadOnlyAdaptersHintName(implementationNamespace),
                        SourceText.From(
                            SparseGeneratedOnceEmitter.RenderReadOnlyAdapters(implementationNamespace, productionContext.CancellationToken),
                            Encoding.UTF8
                        )
                    );
                }
            }
        );
        var needsRemovalIndex = generatedOncePlan
            .Select(static (plan, _) => plan.Has(SparseGeneratedCapability.RemovalIndex))
            .WithComparer(EqualityComparer<bool>.Default)
            .WithTrackingName("SparseTypesGenerator.GeneratedOnceRemovalIndex");
        context.RegisterSourceOutput(
            needsRemovalIndex,
            static (productionContext, emit) =>
            {
                var implementationNamespace = SparseGeneratedOnceEmitter.TryGetNamespace(Configuration);
                if (emit && implementationNamespace is not null)
                {
                    productionContext.AddSource(
                        SparseGeneratedOnceEmitter.RemovalIndexHintName(implementationNamespace),
                        SourceText.From(
                            SparseGeneratedOnceEmitter.RenderRemovalIndex(implementationNamespace, productionContext.CancellationToken),
                            Encoding.UTF8
                        )
                    );
                }
            }
        );
        // Shared JSON kernels back every split-mode fragment and payload
        // converter; single-file legacy output keeps its inline copies.
        // Content follows the JSON families: compilations without them keep
        // an empty shell so the hint set stays stable.
        var needsJsonCodecs = hasModels
            .Combine(stjCapabilities)
            .Select(static (input, _) => (HasModels: input.Left, EmitCodecs: input.Left && input.Right.SupportsV1Wire && EmitsJsonFamily()))
            .WithComparer(EqualityComparer<(bool HasModels, bool EmitCodecs)>.Default)
            .WithTrackingName("SparseTypesGenerator.GeneratedOnceJsonCodecs");
        context.RegisterSourceOutput(
            needsJsonCodecs,
            static (productionContext, emit) =>
            {
                var implementationNamespace = SparseGeneratedOnceEmitter.TryGetNamespace(Configuration);
                if (emit.HasModels && implementationNamespace is not null)
                {
                    productionContext.AddSource(
                        SparseGeneratedOnceEmitter.JsonCodecsHintName(implementationNamespace),
                        SourceText.From(
                            SparseGeneratedOnceEmitter.RenderJsonCodecs(
                                implementationNamespace,
                                Configuration.PatchDialect,
                                emit.EmitCodecs,
                                productionContext.CancellationToken
                            ),
                            Encoding.UTF8
                        )
                    );
                }
            }
        );
        // Key-list and custom-leaf helpers need resolver-era serializer APIs,
        // so they ship behind the payload resolver capability.
        var needsJsonPayloadCodecs = hasModels
            .Combine(stjCapabilities)
            .Select(
                static (input, _) => (HasModels: input.Left, EmitCodecs: input.Left && input.Right.SupportsPayloadJsonResolver && EmitsJsonFamily())
            )
            .WithComparer(EqualityComparer<(bool HasModels, bool EmitCodecs)>.Default)
            .WithTrackingName("SparseTypesGenerator.GeneratedOnceJsonPayloadCodecs");
        context.RegisterSourceOutput(
            needsJsonPayloadCodecs,
            static (productionContext, emit) =>
            {
                var implementationNamespace = SparseGeneratedOnceEmitter.TryGetNamespace(Configuration);
                if (emit.HasModels && implementationNamespace is not null)
                {
                    productionContext.AddSource(
                        SparseGeneratedOnceEmitter.JsonPayloadCodecsHintName(implementationNamespace),
                        SourceText.From(
                            SparseGeneratedOnceEmitter.RenderJsonPayloadCodecs(
                                implementationNamespace,
                                emit.EmitCodecs,
                                productionContext.CancellationToken
                            ),
                            Encoding.UTF8
                        )
                    );
                }
            }
        );

        var shouldEmitIsExternalInit = context
            .CompilationProvider.Combine(context.AnalyzerConfigOptionsProvider)
            .Combine(hasModels)
            .Select(
                static (input, _) =>
                {
                    var ((compilation, options), anyModels) = input;
                    return anyModels && ShouldEmitIsExternalInit(compilation, IsExternalInitEmissionEnabled(options));
                }
            )
            .WithComparer(EqualityComparer<bool>.Default)
            .WithTrackingName("SparseTypesGenerator.IsExternalInit");
        context.RegisterSourceOutput(
            shouldEmitIsExternalInit,
            static (productionContext, emit) =>
            {
                if (emit)
                {
                    productionContext.AddSource(IsExternalInitHintName, SourceText.From(IsExternalInitSource, Encoding.UTF8));
                }
            }
        );
        var shouldEmitNotNullWhen = context
            .CompilationProvider.Combine(hasModels)
            .Select(static (input, _) => input.Right && input.Left.GetTypeByMetadataName(NotNullWhenAttributeName) is null)
            .WithComparer(EqualityComparer<bool>.Default)
            .WithTrackingName("SparseTypesGenerator.NotNullWhen");
        context.RegisterSourceOutput(
            shouldEmitNotNullWhen,
            static (productionContext, emit) =>
            {
                if (emit)
                {
                    productionContext.AddSource(NotNullWhenHintName, SourceText.From(NotNullWhenSource, Encoding.UTF8));
                }
            }
        );

        // Discover mapper declarations and emit default-registration bridges.
        var entityMappers = context
            .SyntaxProvider.ForAttributeWithMetadataName(
                SparseEntityMapperEmitter.MapperAttributeMetadataName,
                static (node, _) => node is TypeDeclarationSyntax,
                static (attributeContext, cancellationToken) =>
                    SparseEntityMapperEmitter.RenderMapper((INamedTypeSymbol)attributeContext.TargetSymbol, cancellationToken)
            )
            .WithTrackingName("SparseTypesGenerator.EntityMappers");
        context.RegisterSourceOutput(entityMappers, static (productionContext, result) => Emit(productionContext, result));
    }

    private static bool IsExternalInitEmissionEnabled(AnalyzerConfigOptionsProvider options) =>
        !options.GlobalOptions.TryGetValue(EmitIsExternalInitOption, out var value)
        || !string.Equals(value, "false", StringComparison.OrdinalIgnoreCase);

    private static bool ShouldEmitIsExternalInit(Compilation compilation, bool configured) =>
        SparseExternalInit.ShouldEmitIsExternalInit(compilation, configured);

    private static void Emit(SourceProductionContext context, SparseGenerationResult result)
    {
        context.CancellationToken.ThrowIfCancellationRequested();
        foreach (var diagnostic in result.Diagnostics)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            context.ReportDiagnostic(
                diagnostic.Arguments.Length <= 1
                    ? Diagnostic.Create(GetDescriptor(diagnostic.DescriptorId), diagnostic.Location ?? Location.None, diagnostic.Argument1)
                    : Diagnostic.Create(GetDescriptor(diagnostic.DescriptorId), diagnostic.Location ?? Location.None, diagnostic.Arguments.ToArray())
            );
        }

        if (result.HintName is not null && result.Source is not null)
        {
            context.AddSource(result.HintName, SourceText.From(result.Source, Encoding.UTF8));
        }

        // Model-facing surface and implementation files share one result so
        // per-model incremental isolation covers both with stable hint names.
        if (!result.AdditionalSources.IsDefaultOrEmpty)
        {
            foreach (var additional in result.AdditionalSources)
            {
                context.CancellationToken.ThrowIfCancellationRequested();
                context.AddSource(additional.HintName, SourceText.From(additional.Source, Encoding.UTF8));
            }
        }
    }

    private static SparseGenerationResult Render(
        SparseGenerationAnalysis analysis,
        bool bclHashSetImplementsReadOnlySet,
        bool bclHashSetSupportsCapacity,
        bool allowFileScopedTypes,
        SparseStjCapabilities stjCapabilities,
        CancellationToken cancellationToken
    )
    {
        cancellationToken.ThrowIfCancellationRequested();
        if (!analysis.Model.HasValue)
        {
            return new SparseGenerationResult(null, null, analysis.Diagnostics);
        }

        var model = analysis.Model.Value;
        var configuration = WithCapabilities(Configuration, allowFileScopedTypes, stjCapabilities);
        var implementationNamespace = SparseGeneratedPlacement.TryGetImplementationNamespace(configuration);
        Action<SharedIndentedBuilder>? appendModelMembers = null;
        if (implementationNamespace is not null)
        {
            var runtime = configuration.RuntimeDialect ?? throw new InvalidOperationException("A runtime dialect is required for source emission.");
            appendModelMembers = code =>
                SparseModelImplementationEmitter.AppendModelMembers(
                    code,
                    model,
                    analysis.Members,
                    analysis.ReadOnlyViewModels,
                    configuration,
                    runtime.Namespace,
                    implementationNamespace
                );
        }

        // Keep each model's surface and implementation in one file; only
        // compilation-scoped Generated-Once helpers use separate files.
        var (surface, implementation) = SparsePerModelEmitter.BuildSplitSurface(
            model,
            analysis.Members,
            analysis.PocoCloneModels,
            analysis.ReadOnlyViewModels,
            analysis.StructuralModels,
            bclHashSetImplementsReadOnlySet,
            bclHashSetSupportsCapacity,
            cancellationToken,
            configuration,
#if SPARSE_FRAGMENTS
            null,
#else
            (code, generatedModel, members) => SparseModelExtensionsEmitter.Append(code, generatedModel, members, configuration),
#endif
            analysis.PayloadJsonPocos,
            appendModelMembers,
            analysis.PayloadContract
        );
        var additional = ImmutableArray<SparseGeneratedSource>.Empty;
        if (implementation.HasValue)
        {
            additional = additional.Add(implementation.Value);
        }

        var merged = MergePerModelSources(surface, additional);
        return new SparseGenerationResult(model.HintName, merged, analysis.Diagnostics, ImmutableArray<SparseGeneratedSource>.Empty);
    }

